#!/usr/bin/env node
/**
 * Generate Prerender Routes for Market Material Pages
 * 
 * This script fetches active market_materials from Supabase and generates
 * a routes.json file for vite-plugin-prerender or similar tools.
 * 
 * Run: node scripts/generate-prerender-routes.mjs
 */

import { createClient } from '@supabase/supabase-js';
import { writeFileSync, mkdirSync, existsSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __filename = fileURLToPath(import.meta.url);
const __dirname = dirname(__filename);

// Supabase configuration
const SUPABASE_URL = 'https://losrkjvrcambvgijfism.supabase.co';
const SUPABASE_ANON_KEY = 'eyJhbGciOiJIUzI1NiIsInR5cCI6IkpXVCJ9.eyJpc3MiOiJzdXBhYmFzZSIsInJlZiI6Imxvc3JranZyY2FtYnZnaWpmaXNtIiwicm9sZSI6ImFub24iLCJpYXQiOjE3NDU4OTI0NjIsImV4cCI6MjA2MTQ2ODQ2Mn0.LdtyGNA5PmayO9VYcNRsO12DCAg0iS460rtTsDsS5B8';

const supabase = createClient(SUPABASE_URL, SUPABASE_ANON_KEY);

// Static routes that should always be prerendered
const STATIC_ROUTES = [
  '/',
  '/products',
  '/calculator',
  '/contact',
  '/about',
  '/faq',
  '/blog',
  '/reviews',
  '/locations',
  '/privacy-policy',
  '/terms-of-service',
  '/refund-policy',
];

async function fetchActiveMarketMaterialRoutes() {
  console.log('Fetching active market material pages...');
  
  const { data, error } = await supabase
    .from('market_materials')
    .select('slug_path')
    .eq('status', 'active')
    .not('slug_path', 'is', null);

  if (error) {
    console.error('Error fetching market materials:', error);
    return [];
  }

  // Convert slug_path to route format (e.g., "markets/nashville-tn/materials/57-crushed-stone" -> "/markets/nashville-tn/materials/57-crushed-stone")
  return (data || []).map(row => `/${row.slug_path}`);
}

async function fetchBlogPostRoutes() {
  console.log('Fetching blog posts...');
  
  const { data, error } = await supabase
    .from('blog_posts')
    .select('slug')
    .not('published_at', 'is', null);

  if (error) {
    console.error('Error fetching blog posts:', error);
    return [];
  }

  return (data || []).map(row => `/blog/${row.slug}`);
}

async function fetchLocationRoutes() {
  console.log('Fetching delivery locations...');
  
  const { data, error } = await supabase
    .from('delivery_locations')
    .select('slug')
    .not('slug', 'is', null);

  if (error) {
    console.error('Error fetching locations:', error);
    return [];
  }

  return (data || []).map(row => `/locations/${row.slug}`);
}

async function fetchProductRoutes() {
  console.log('Fetching products...');
  
  const { data, error } = await supabase
    .from('products')
    .select('slug')
    .not('slug', 'is', null);

  if (error) {
    console.error('Error fetching products:', error);
    return [];
  }

  return (data || []).map(row => `/products/${row.slug}`);
}

async function main() {
  console.log('🚀 Generating prerender routes...\n');

  // Fetch all dynamic routes in parallel
  const [marketMaterialRoutes, blogRoutes, locationRoutes, productRoutes] = await Promise.all([
    fetchActiveMarketMaterialRoutes(),
    fetchBlogPostRoutes(),
    fetchLocationRoutes(),
    fetchProductRoutes(),
  ]);

  // Combine all routes
  const allRoutes = [
    ...STATIC_ROUTES,
    ...marketMaterialRoutes,
    ...blogRoutes,
    ...locationRoutes,
    ...productRoutes,
  ];

  // Remove duplicates
  const uniqueRoutes = [...new Set(allRoutes)].sort();

  console.log(`\n📊 Route Summary:`);
  console.log(`   Static routes: ${STATIC_ROUTES.length}`);
  console.log(`   Market material pages: ${marketMaterialRoutes.length}`);
  console.log(`   Blog posts: ${blogRoutes.length}`);
  console.log(`   Locations: ${locationRoutes.length}`);
  console.log(`   Products: ${productRoutes.length}`);
  console.log(`   Total unique routes: ${uniqueRoutes.length}\n`);

  // Ensure output directory exists
  const outputDir = join(__dirname, '..', 'prebuild');
  if (!existsSync(outputDir)) {
    mkdirSync(outputDir, { recursive: true });
  }

  // Write routes.json
  const outputPath = join(outputDir, 'routes.json');
  writeFileSync(outputPath, JSON.stringify(uniqueRoutes, null, 2));
  console.log(`✅ Routes written to: ${outputPath}`);

  // Also export as module for vite config
  const moduleOutputPath = join(outputDir, 'routes.mjs');
  writeFileSync(moduleOutputPath, `// Auto-generated by generate-prerender-routes.mjs
export const routes = ${JSON.stringify(uniqueRoutes, null, 2)};
export default routes;
`);
  console.log(`✅ Routes module written to: ${moduleOutputPath}`);

  return uniqueRoutes;
}

main().catch(console.error);
